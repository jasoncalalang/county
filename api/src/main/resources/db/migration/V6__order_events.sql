-- W3: who did what to an order, and when. One row per successful order action, written in the
-- transaction that changes the order. Orders changed before this migration have no events.
CREATE TABLE order_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL,
 order_id BIGINT NOT NULL,
 at TIMESTAMPTZ NOT NULL,
 from_status VARCHAR(10) NOT NULL CHECK (from_status IN ('placed','confirmed','delivered','cancelled')),
 to_status VARCHAR(10) NOT NULL CHECK (to_status IN ('placed','confirmed','delivered','cancelled')),
 paid BOOLEAN NOT NULL,
 actor_type VARCHAR(8) NOT NULL CHECK (actor_type IN ('owner','reseller')),
 actor_user_id BIGINT REFERENCES app_user(id),
 actor_reseller_id BIGINT,
 FOREIGN KEY (tenant_id, order_id) REFERENCES sales_order(tenant_id, id),
 FOREIGN KEY (tenant_id, actor_reseller_id) REFERENCES reseller(tenant_id, id),
 CHECK ((actor_type = 'owner' AND actor_user_id IS NOT NULL AND actor_reseller_id IS NULL)
     OR (actor_type = 'reseller' AND actor_reseller_id IS NOT NULL AND actor_user_id IS NULL))
);
CREATE INDEX order_event_order_idx ON order_event (tenant_id, order_id, at, id);

-- History is append-only: nothing changes or removes an event after the fact.
CREATE FUNCTION order_event_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'order_event is append-only';
END;
$$;
CREATE TRIGGER order_event_append_only BEFORE UPDATE OR DELETE ON order_event
  FOR EACH ROW EXECUTE FUNCTION order_event_append_only();
