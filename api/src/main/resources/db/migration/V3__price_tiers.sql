-- Per-reseller price tiers (Beyond-v1, derived from the Itemcount reference).
-- A tier names a per-product price override; a reseller assigned to a tier is charged the
-- tier price, falling back to the product's base price where no override exists. Captured
-- order-line prices are unaffected (ADR 0012): the tier only sets the price used at placement.
CREATE TABLE price_tier (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES business(id),
 name VARCHAR(80) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE (tenant_id, id)
);
CREATE UNIQUE INDEX unique_active_price_tier ON price_tier(tenant_id, lower(name)) WHERE active;

-- A reseller's tier. Null means the base price. The composite foreign key keeps the tier in
-- the reseller's own tenant; with price_tier_id null the key is not enforced (MATCH SIMPLE).
ALTER TABLE reseller ADD COLUMN price_tier_id BIGINT;
ALTER TABLE reseller ADD CONSTRAINT reseller_price_tier_fk
 FOREIGN KEY (tenant_id, price_tier_id) REFERENCES price_tier(tenant_id, id);

CREATE TABLE product_tier_price (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 price_tier_id BIGINT NOT NULL,
 price NUMERIC(12,2) NOT NULL CHECK (price > 0),
 UNIQUE (tenant_id, product_id, price_tier_id),
 FOREIGN KEY (tenant_id, product_id) REFERENCES product(tenant_id, id),
 FOREIGN KEY (tenant_id, price_tier_id) REFERENCES price_tier(tenant_id, id)
);
CREATE INDEX product_tier_price_by_tier ON product_tier_price(tenant_id, price_tier_id);
