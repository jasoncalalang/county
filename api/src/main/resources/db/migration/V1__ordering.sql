CREATE TABLE business (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_subject TEXT NOT NULL UNIQUE,
 name VARCHAR(80) NOT NULL,
 cutoff TIME NOT NULL,
 delivery_days INTEGER[] NOT NULL,
 next_order_number BIGINT NOT NULL DEFAULT 1,
 CHECK (cardinality(delivery_days)>0)
);
CREATE TABLE product (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES business(id),
 name VARCHAR(80) NOT NULL,
 unit VARCHAR(4) NOT NULL CHECK (unit IN ('pack','kg','pc')),
 price NUMERIC(12,2) NOT NULL CHECK (price>0),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE (tenant_id,id)
);
CREATE UNIQUE INDEX unique_active_product ON product(tenant_id,lower(name)) WHERE active;
CREATE TABLE reseller (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES business(id),
 name VARCHAR(80) NOT NULL,
 mobile VARCHAR(13) NOT NULL,
 token VARCHAR(22) NOT NULL UNIQUE,
 status VARCHAR(8) NOT NULL DEFAULT 'invited' CHECK(status IN ('invited','active','blocked')),
 has_ordered BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(tenant_id,mobile), UNIQUE(tenant_id,id)
);
CREATE TABLE purchase_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES business(id),
 reseller_id BIGINT NOT NULL,
 number BIGINT NOT NULL,
 placed_at TIMESTAMPTZ NOT NULL,
 delivery_date DATE NOT NULL,
 status VARCHAR(10) NOT NULL DEFAULT 'placed' CHECK(status IN ('placed','confirmed','delivered','cancelled')),
 total NUMERIC(12,2) NOT NULL,
 note VARCHAR(500) NOT NULL DEFAULT '',
 paid BOOLEAN NOT NULL DEFAULT FALSE,
 idempotency_key UUID NOT NULL,
 confirmed_at TIMESTAMPTZ, delivered_at TIMESTAMPTZ, cancelled_at TIMESTAMPTZ, paid_at TIMESTAMPTZ,
 FOREIGN KEY(tenant_id,reseller_id) REFERENCES reseller(tenant_id,id),
 UNIQUE(tenant_id,number), UNIQUE(tenant_id,idempotency_key), UNIQUE(tenant_id,id)
);
CREATE TABLE order_line (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL,
 order_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 product_name VARCHAR(80) NOT NULL,
 unit VARCHAR(4) NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 9999),
 price NUMERIC(12,2) NOT NULL,
 total NUMERIC(12,2) NOT NULL,
 FOREIGN KEY(tenant_id,order_id) REFERENCES purchase_order(tenant_id,id),
 FOREIGN KEY(tenant_id,product_id) REFERENCES product(tenant_id,id),
 UNIQUE(order_id,product_id)
);
CREATE INDEX order_delivery ON purchase_order(tenant_id,delivery_date,status);
CREATE INDEX reseller_recent ON purchase_order(tenant_id,reseller_id,placed_at DESC);
