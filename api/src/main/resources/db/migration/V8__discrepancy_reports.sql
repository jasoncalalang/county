-- Short-delivery reports (ADR 0012): what was actually received, filed by the owner or the
-- reseller against a delivered order and resolved by the other party. A separate record: the
-- order, its lines and its total never change. One report per order.
CREATE TABLE discrepancy_report (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL REFERENCES business(id),
 order_id BIGINT NOT NULL,
 filed_by VARCHAR(8) NOT NULL CHECK (filed_by IN ('owner','reseller')),
 filed_at TIMESTAMPTZ NOT NULL,
 status VARCHAR(8) NOT NULL DEFAULT 'open' CHECK (status IN ('open','approved','declined')),
 note VARCHAR(500) NOT NULL DEFAULT '',
 resolution_note VARCHAR(500) NOT NULL DEFAULT '',
 resolved_by VARCHAR(8) CHECK (resolved_by IN ('owner','reseller')),
 resolved_at TIMESTAMPTZ,
 shortfall_total NUMERIC(12,2) NOT NULL,
 idempotency_key UUID NOT NULL,
 FOREIGN KEY (tenant_id, order_id) REFERENCES sales_order(tenant_id, id),
 UNIQUE (tenant_id, order_id),
 UNIQUE (tenant_id, idempotency_key),
 UNIQUE (tenant_id, id),
 CHECK ((status = 'open' AND resolved_by IS NULL AND resolved_at IS NULL)
     OR (status <> 'open' AND resolved_by IS NOT NULL AND resolved_at IS NOT NULL)),
 CHECK (resolved_by IS NULL OR resolved_by <> filed_by)
);
CREATE INDEX discrepancy_report_status_idx ON discrepancy_report (tenant_id, status, filed_at DESC);

-- A line copies the order line's name, unit, quantity and price, so the record stands even if the
-- product is edited or deactivated. A negative shortfall is over-delivery.
CREATE TABLE discrepancy_line (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL,
 report_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 product_name VARCHAR(80) NOT NULL,
 unit VARCHAR(4) NOT NULL CHECK (unit IN ('pack','kg','pc')),
 ordered_quantity NUMERIC(7,3) NOT NULL,
 received_quantity NUMERIC(7,3) NOT NULL CHECK (received_quantity >= 0 AND received_quantity <= 9999),
 price NUMERIC(12,2) NOT NULL,
 shortfall_total NUMERIC(12,2) NOT NULL,
 FOREIGN KEY (tenant_id, report_id) REFERENCES discrepancy_report(tenant_id, id),
 FOREIGN KEY (tenant_id, product_id) REFERENCES product(tenant_id, id),
 UNIQUE (report_id, product_id)
);
