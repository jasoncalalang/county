-- Retain existing owner access while replacing the Google-subject shortcut with
-- the accepted provider/subject identity model. Never link users by email.
CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 display_name TEXT,
 email TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE external_identity (
 provider TEXT NOT NULL,
 subject TEXT NOT NULL,
 user_id BIGINT NOT NULL REFERENCES app_user(id),
 PRIMARY KEY(provider,subject),
 CHECK (length(provider)>0 AND length(subject)>0)
);
CREATE INDEX identity_user ON external_identity(user_id);
